const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const lifecycle = process.env.npm_lifecycle_event || ''
const mode = process.env.MODE || process.env.NODE_ENV || (lifecycle.includes('build') ? 'production' : 'development')
const envFiles = [
  '.env',
  '.env.local',
  `.env.${mode}`,
  `.env.${mode}.local`,
]

function loadDotEnv() {
  for (const envFile of envFiles) {
    const envPath = path.join(root, envFile)
    if (!fs.existsSync(envPath)) continue
    const lines = fs.readFileSync(envPath, 'utf8').split(/\r?\n/)
    for (const line of lines) {
      const trimmed = line.trim()
      if (!trimmed || trimmed.startsWith('#') || !trimmed.includes('=')) continue
      const index = trimmed.indexOf('=')
      const key = trimmed.slice(0, index).trim()
      const value = trimmed.slice(index + 1).trim().replace(/^['"]|['"]$/g, '')
      process.env[key] = value
    }
  }
}

loadDotEnv()

const config = {
  apiKey: process.env.VITE_FIREBASE_API_KEY || '',
  authDomain: process.env.VITE_FIREBASE_AUTH_DOMAIN || '',
  projectId: process.env.VITE_FIREBASE_PROJECT_ID || '',
  storageBucket: process.env.VITE_FIREBASE_STORAGE_BUCKET || '',
  messagingSenderId: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID || '',
  appId: process.env.VITE_FIREBASE_APP_ID || '',
}

const missing = Object.entries(config).filter(([, value]) => !value).map(([key]) => key)
if (missing.length) {
  console.warn(`[fcm-sw] Missing Firebase config values: ${missing.join(', ')}`)
}

const content = `/* Generated by scripts/generate-fcm-sw.cjs. Do not edit by hand. */
importScripts('https://www.gstatic.com/firebasejs/10.8.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.8.0/firebase-messaging-compat.js');

firebase.initializeApp(${JSON.stringify(config, null, 2)});

const messaging = firebase.messaging();

const PUSH_ICON = 'https://res.cloudinary.com/doawldbnh/image/upload/w_192,h_192,c_fit,f_png,q_auto/v1792509878/v5xliyxwuirgzhp6ict6.png';

messaging.onBackgroundMessage((payload) => {
  const data = payload.data || {};
  const notification = payload.notification || {};

  const title = notification.title || data.title || 'Paw Paw Pet Grooming';
  const body = notification.body || data.body || '';
  if (!title && !body) return;

  const tag = data.tag || data.bookingId || 'pawpaw-alert';
  const targetUrl = data.actionUrl || data.link || '/';
  const actionTitle = data.actionTitle || (targetUrl.includes('boarding') ? '🐾 View Boarding' : '📅 View Booking');

  const options = {
    body: body,
    icon: data.icon || PUSH_ICON,
    tag: tag,
    renotify: true,
    vibrate: [200, 100, 200],
    requireInteraction: true,
    data: {
      url: targetUrl,
    },
    actions: [
      { action: 'open_url', title: actionTitle },
      { action: 'dismiss', title: 'Dismiss' },
    ],
  };

  return self.registration.showNotification(title, options);
});

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  if (event.action === 'dismiss') return;

  const rawUrl = event.notification?.data?.url || '/';
  const url = rawUrl.startsWith('http') ? rawUrl : new URL(rawUrl, self.location.origin).href;

  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windowClients) => {
      for (const client of windowClients) {
        if (client.url.includes(self.location.origin) && 'focus' in client) {
          if ('navigate' in client) {
            client.navigate(url);
          }
          return client.focus();
        }
      }
      if (clients.openWindow) {
        return clients.openWindow(url);
      }
    })
  );
});
`

const outPath = path.join(root, 'public', 'firebase-messaging-sw.js')
fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, content)
console.log(`[fcm-sw] Wrote ${path.relative(root, outPath)} using ${mode} env`)
